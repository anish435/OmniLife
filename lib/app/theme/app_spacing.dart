/// Centralized spacing scale. Widgets should use these constants instead
/// of ad-hoc pixel values so spacing stays consistent across the app.
abstract final class AppSpacing {
  static const xs = 4.0;
  static const sm = 8.0;
  static const md = 16.0;
  static const lg = 24.0;
  static const section = 32.0;
  static const screenPadding = 20.0;
}
